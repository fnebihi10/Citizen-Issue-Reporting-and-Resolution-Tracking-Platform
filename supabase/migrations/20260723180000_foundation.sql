create or replace function public.protect_profile_privileged_fields()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if not public.is_admin() and (
    new.role is distinct from old.role
    or new.department_id is distinct from old.department_id
    or new.email is distinct from old.email
    or new.id is distinct from old.id
  ) then
    raise exception 'Only an administrator can change privileged profile fields';
  end if;
  return new;
end;
$$;

create trigger profiles_protect_privileged_fields before update on public.profiles
  for each row execute function public.protect_profile_privileged_fields();

create or replace function public.prepare_report()
returns trigger
language plpgsql
set search_path = public
as $$
declare
  category_sla smallint;
begin
  select c.default_sla_hours into category_sla
  from public.categories c
  where c.id = new.category_id and c.is_active = true;

  if category_sla is null then
    raise exception 'Category is missing or inactive';
  end if;

  if tg_op = 'INSERT' then
    if new.status <> 'submitted' or new.priority <> 'normal' or new.is_public then
      raise exception 'A new citizen report must start as submitted, normal and private';
    end if;
    new.sla_due_at = now() + make_interval(hours => category_sla);
  end if;

  if new.status = 'resolved' and nullif(trim(new.resolution_notes), '') is null then
    raise exception 'Resolution notes are required before resolving a report';
  end if;

  if new.status = 'rejected' and nullif(trim(new.rejected_reason), '') is null then
    raise exception 'A rejection reason is required';
  end if;

  if new.is_public and new.public_location is null then
    raise exception 'A public report must have a privacy-safe public location';
  end if;

  return new;
end;
$$;

create trigger reports_prepare before insert or update on public.reports
  for each row execute function public.prepare_report();

create or replace function public.validate_report_status_transition()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  if new.status = old.status then
    return new;
  end if;

  if not (
    (old.status = 'submitted' and new.status = 'under_review')
    or (old.status = 'under_review' and new.status in ('assigned', 'rejected'))
    or (old.status = 'assigned' and new.status = 'in_progress')
    or (old.status = 'in_progress' and new.status = 'resolved')
    or (old.status = 'resolved' and new.status = 'reopened')
    or (old.status = 'reopened' and new.status = 'under_review')
  ) then
    raise exception 'Invalid report status transition: % -> %', old.status, new.status;
  end if;

  if new.status = 'resolved' then
    new.resolved_at = coalesce(new.resolved_at, now());
  elsif old.status = 'resolved' and new.status = 'reopened' then
    new.resolved_at = null;
  end if;

  return new;
end;
$$;

create trigger reports_validate_status before update of status on public.reports
  for each row execute function public.validate_report_status_transition();

create or replace function public.record_report_status_change()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if tg_op = 'INSERT' then
    insert into public.report_status_history (report_id, previous_status, new_status, changed_by)
    values (new.id, null, new.status, auth.uid());
  elsif new.status is distinct from old.status then
    insert into public.report_status_history (report_id, previous_status, new_status, changed_by)
    values (new.id, old.status, new.status, auth.uid());
  end if;
  return new;
end;
$$;

create trigger reports_record_status_change after insert or update of status on public.reports
  for each row execute function public.record_report_status_change();

create or replace function public.audit_report_change()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.audit_logs (actor_id, action, entity_type, entity_id, details)
  values (
    auth.uid(),
    case when tg_op = 'INSERT' then 'report.created' else 'report.updated' end,
    'report',
    new.id,
    jsonb_build_object(
      'report_number', new.report_number,
      'operation', tg_op,
      'status', new.status,
      'department_id', new.department_id,
      'assigned_official_id', new.assigned_official_id,
      'is_public', new.is_public
    )
  );
  return new;
end;
$$;

create trigger reports_audit_change after insert or update on public.reports
  for each row execute function public.audit_report_change();

-- Public views intentionally exclude citizen_id, author_id, email, phone and exact private location.
create or replace view public.public_reports
with (security_barrier = true)
as
select
  r.id,
  r.report_number,
  coalesce(r.public_title, 'Raportim qytetar') as title,
  r.public_summary as summary,
  c.slug as category_slug,
  c.name as category_name,
  r.status,
  r.priority,
  extensions.st_x(r.public_location::extensions.geometry) as longitude,
  extensions.st_y(r.public_location::extensions.geometry) as latitude,
  r.created_at,
  r.updated_at,
  r.resolved_at
from public.reports r
join public.categories c on c.id = r.category_id
where r.is_public = true and r.public_location is not null;

create or replace view public.public_report_comments
with (security_barrier = true)
as
select
  rc.id,
  rc.report_id,
  rc.body,
  case when p.role = 'citizen' then 'Qytetar' else 'Zyrtar komunal' end as author_label,
  rc.created_at
from public.report_comments rc
join public.profiles p on p.id = rc.author_id
where rc.is_internal = false;

create or replace view public.public_report_status_history
with (security_barrier = true)
as
select id, report_id, previous_status, new_status, created_at
from public.report_status_history;

