create table public.departments (
  id uuid primary key default gen_random_uuid(),
  name text not null unique,
  code text not null unique,
  description text,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint departments_code_format check (code ~ '^[A-Z0-9_-]{2,12}$'),
  constraint departments_name_length check (char_length(trim(name)) between 2 and 120)
);

create table public.categories (
  id uuid primary key default gen_random_uuid(),
  slug text not null unique,
  name text not null unique,
  icon_key text not null default 'alert-circle',
  default_sla_hours smallint not null default 48,
  department_id uuid references public.departments(id) on delete set null,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint categories_slug_format check (slug ~ '^[a-z0-9]+(?:-[a-z0-9]+)*$'),
  constraint categories_sla_range check (default_sla_hours between 1 and 8760),
  constraint categories_name_length check (char_length(trim(name)) between 2 and 80)
);

-- This table extends auth.users. The role is never read from user metadata.
create table public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  email text not null unique,
  full_name text not null default 'Qytetar',
  phone text,
  role public.user_role not null default 'citizen',
  department_id uuid references public.departments(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint profiles_email_length check (char_length(email) between 3 and 320),
  constraint profiles_name_length check (char_length(trim(full_name)) between 2 and 120)
);

create table public.reports (
  id uuid primary key default gen_random_uuid(),
  report_number bigint generated by default as identity unique,
  title text not null,
  description text not null,
  category_id uuid not null references public.categories(id) on delete restrict,
  department_id uuid references public.departments(id) on delete set null,
  assigned_official_id uuid references auth.users(id) on delete set null,
  citizen_id uuid not null references auth.users(id) on delete restrict,
  status public.report_status not null default 'submitted',
  priority public.report_priority not null default 'normal',
  location extensions.geography(Point, 4326) not null,
  address_text text,
  sla_due_at timestamptz not null default now(),
  is_public boolean not null default false,
  public_title text,
  public_summary text,
  public_location extensions.geography(Point, 4326),
  resolution_notes text,
  rejected_reason text,
  resolved_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint reports_title_length check (char_length(trim(title)) between 5 and 160),
  constraint reports_description_length check (char_length(trim(description)) between 10 and 5000),
  constraint reports_public_title_length check (public_title is null or char_length(trim(public_title)) between 5 and 160),
  constraint reports_public_summary_length check (public_summary is null or char_length(trim(public_summary)) between 10 and 1000),
  constraint reports_public_requirements check (
    (is_public = false and public_location is null)
    or (is_public = true and public_location is not null)
  )
);

create table public.report_status_history (
  id uuid primary key default gen_random_uuid(),
  report_id uuid not null references public.reports(id) on delete cascade,
  previous_status public.report_status,
  new_status public.report_status not null,
  changed_by uuid references auth.users(id) on delete set null,
  note text,
  created_at timestamptz not null default now(),
  constraint report_status_history_note_length check (note is null or char_length(note) <= 2000)
);

create table public.report_comments (
  id uuid primary key default gen_random_uuid(),
  report_id uuid not null references public.reports(id) on delete cascade,
  author_id uuid not null references auth.users(id) on delete restrict,
  body text not null,
  is_internal boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint report_comments_body_length check (char_length(trim(body)) between 1 and 2000)
);

create table public.report_attachments (
  id uuid primary key default gen_random_uuid(),
  report_id uuid not null references public.reports(id) on delete cascade,
  uploaded_by uuid not null references auth.users(id) on delete restrict,
  bucket_id text not null default 'report-evidence',
  object_path text not null unique,
  kind public.attachment_kind not null default 'evidence',
  mime_type text not null,
  size_bytes integer not null,
  created_at timestamptz not null default now(),
  constraint report_attachments_bucket check (bucket_id = 'report-evidence'),
  constraint report_attachments_mime check (mime_type in ('image/jpeg', 'image/png', 'image/webp')),
  constraint report_attachments_size check (size_bytes between 1 and 10485760),
  constraint report_attachments_path check (object_path ~ '^reports/[0-9a-fA-F-]{36}/[^/]+$')
);

create table public.notifications (
  id uuid primary key default gen_random_uuid(),
  recipient_id uuid not null references auth.users(id) on delete cascade,
  report_id uuid references public.reports(id) on delete cascade,
  type text not null,
  title text not null,
  message text not null,
  read_at timestamptz,
  created_at timestamptz not null default now(),
  constraint notifications_text_length check (
    char_length(trim(type)) between 2 and 60
    and char_length(trim(title)) between 2 and 160
    and char_length(trim(message)) between 1 and 1000
  )
);

create table public.audit_logs (
  id uuid primary key default gen_random_uuid(),
  actor_id uuid references auth.users(id) on delete set null,
  action text not null,
  entity_type text not null,
  entity_id uuid,
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  constraint audit_logs_action_length check (char_length(trim(action)) between 2 and 80),
  constraint audit_logs_entity_length check (char_length(trim(entity_type)) between 2 and 80)
);

